  /* ---------- Lookup ---------- */
  function t(lang, enText) {
    if (!enText) return enText;
    var table = DICT[lang];
    if (!table) return enText;
    return Object.prototype.hasOwnProperty.call(table, enText) ? table[enText] : enText;
  }

  function isSupported(code) {
    return CODES.indexOf(code) !== -1;
  }

  function meta(code) {
    return byCode[code] || byCode.en;
  }

  function isRTL(code) {
    return !!(meta(code).rtl);
  }

  /* ---------- Auto-detection ----------
     Walk the browser's preferred languages in order and take the first
     one we actually ship. `bn-BD` matches `bn`; `es-419` matches `es`.
     Falls back to English so the page is never blank. */
  function detect() {
    var prefs = [];
    try {
      if (navigator.languages && navigator.languages.length) {
        prefs = prefs.concat(Array.prototype.slice.call(navigator.languages));
      }
      if (navigator.language) prefs.push(navigator.language);
    } catch (e) { /* ignore */ }

    for (var i = 0; i < prefs.length; i++) {
      var raw = String(prefs[i] || "").toLowerCase().replace(/_/g, "-");
      if (!raw) continue;
      if (isSupported(raw)) return raw;
      var base = raw.split("-")[0];
      if (isSupported(base)) return base;
    }
    return "en";
  }

  /* ---------- Persisted choice ----------
     A manual selection always wins over auto-detection. We deliberately
     do NOT store an auto-detected language, so a visitor who later opens
     the site from another country gets that country's language. */
  var KEY = "ps_lang";

  function getStored() {
    try {
      var v = localStorage.getItem(KEY);
      return isSupported(v) ? v : null;
    } catch (e) { return null; }
  }

  function store(code) {
    try {
      if (code) localStorage.setItem(KEY, code);
      else localStorage.removeItem(KEY);
    } catch (e) { /* ignore */ }
  }

  global.I18N = {
    LANGS: LANGS,
    CODES: CODES,
    t: t,
    detect: detect,
    isSupported: isSupported,
    meta: meta,
    isRTL: isRTL,
    getStored: getStored,
    store: store
  };
